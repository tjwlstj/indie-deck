test('receipt write failure restores all pre-operation payload and old receipt bytes from the retained quarantine', async () => {
  const profile = game('receipt-fault');
  own(profile, createEntries(profile.path, [PLUGIN, COMMON, CONFIG]));
  const originalReceipt = bytes(profile.path, RECEIPT);
  const preview = await previewTranslatorMaintenance(reg, profile);
  const originalOpen = fsp.open;
  let failOnce = true;
  fsp.open = (async (...args: Parameters<typeof fsp.open>) => {
    if (String(args[0]) === path.join(profile.path, RECEIPT) && typeof args[1] === 'number' && (args[1] & 3) === 2 && failOnce) {
      failOnce = false; throw new Error('isolated receipt write failure');
    }
    return originalOpen(...args);
  }) as typeof fsp.open;
  try {
    await withDownload(preview, replacement(), async () => {
      await assert.rejects(runTranslatorMaintenance(preview, 'reinstall', cache('receipt-fault')), (error: unknown) => {
        const result = (error as { maintenanceResult?: { mutationStatus: string; rollbackStatus: string; backupDirectory: string } }).maintenanceResult;
        assert.equal(result?.mutationStatus, 'rolled-back');
        assert.equal(result?.rollbackStatus, 'complete');
        assert.ok(fs.existsSync(result!.backupDirectory));
        return true;
      });
    });
  } finally { fsp.open = originalOpen; }
  assert.deepEqual(bytes(profile.path, RECEIPT), originalReceipt);
  assert.deepEqual(bytes(profile.path, PLUGIN), dllWithVersion('5.5.2'));
  assert.deepEqual(bytes(profile.path, COMMON), dllWithVersion('5.5.2'));
  assert.equal(bytes(profile.path, CONFIG).toString(), USER_CONFIG);
});

test('a recovery I/O failure reports partial state honestly and retains the pre-operation backup', async () => {
  const profile = game('partial-recovery');
  own(profile, createEntries(profile.path, [PLUGIN, COMMON, CONFIG]));
  const preview = await previewTranslatorMaintenance(reg, profile);
  const originalOpen = fsp.open, originalWrite = fsp.writeFile;
  let failReceipt = true;
  fsp.open = (async (...args: Parameters<typeof fsp.open>) => {
    if (String(args[0]) === path.join(profile.path, RECEIPT) && typeof args[1] === 'number' && (args[1] & 3) === 2 && failReceipt) {
      failReceipt = false; throw new Error('isolated receipt commit failure');
    }
    return originalOpen(...args);
  }) as typeof fsp.open;
  fsp.writeFile = (async (...args: Parameters<typeof fsp.writeFile>) => {
    if (String(args[0]) === path.join(profile.path, PLUGIN)) throw new Error('isolated recovery write failure');
    return originalWrite(...args);
  }) as typeof fsp.writeFile;
  try {
    await withDownload(preview, replacement(), async () => {
      await assert.rejects(runTranslatorMaintenance(preview, 'reinstall', cache('partial-recovery')), (error: unknown) => {
        const result = (error as { maintenanceResult?: { mutationStatus: string; rollbackStatus: string; backupDirectory: string; rollbackFailures: { path: string }[] } }).maintenanceResult;
        assert.equal(result?.mutationStatus, 'partial');
        assert.equal(result?.rollbackStatus, 'partial');
        assert.ok(result?.rollbackFailures.some((failure) => failure.path === PLUGIN));
        assert.deepEqual(fs.readFileSync(path.join(result!.backupDirectory, 'files', PLUGIN)), dllWithVersion('5.5.2'));
        return true;
      });
    });
  } finally { fsp.open = originalOpen; fsp.writeFile = originalWrite; }
  assert.equal(bytes(profile.path, CONFIG).toString(), USER_CONFIG);
  assert.equal(bytes(profile.path, OTHER).toString(), 'another user-owned mod');
});

