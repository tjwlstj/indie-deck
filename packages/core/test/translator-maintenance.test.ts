const bytes = (root: string, rel: string) => fs.readFileSync(path.join(root, rel));

function crc32(buffer: Buffer): number {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function zip(files: Record<string, string | Buffer>, deflate = false, declaredSize?: number): Buffer {
  const locals: Buffer[] = [], centrals: Buffer[] = [];
  let offset = 0;
  for (const [name, value] of Object.entries(files)) {
    const data = Buffer.isBuffer(value) ? value : Buffer.from(value);
    const compressed = deflate ? zlib.deflateRawSync(data) : data;
    const encoded = Buffer.from(name);
    const local = Buffer.alloc(30 + encoded.length), central = Buffer.alloc(46 + encoded.length);
    local.writeUInt32LE(0x04034b50, 0); local.writeUInt16LE(20, 4);
    local.writeUInt16LE(deflate ? 8 : 0, 8);
    local.writeUInt32LE(crc32(data), 14); local.writeUInt32LE(compressed.length, 18); local.writeUInt32LE(declaredSize ?? data.length, 22);
    local.writeUInt16LE(encoded.length, 26); encoded.copy(local, 30);
    central.writeUInt32LE(0x02014b50, 0); central.writeUInt16LE(20, 4); central.writeUInt16LE(20, 6);
    central.writeUInt16LE(deflate ? 8 : 0, 10);
    central.writeUInt32LE(crc32(data), 16); central.writeUInt32LE(compressed.length, 20); central.writeUInt32LE(declaredSize ?? data.length, 24);
    central.writeUInt16LE(encoded.length, 28); central.writeUInt32LE(offset, 42); encoded.copy(central, 46);
    locals.push(local, compressed); centrals.push(central); offset += local.length + compressed.length;
  }
  const cd = Buffer.concat(centrals), end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(centrals.length, 8); end.writeUInt16LE(centrals.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}

async function withDownload<T>(preview: TranslatorMaintenancePreview, payload: Buffer, action: () => Promise<T>, duringDownload?: () => void): Promise<T> {
  const original = globalThis.fetch;
  const asset = preview.context.plan?.steps.find((step) => step.action === 'download')?.source?.asset;
  assert.ok(asset, 'the fixture resolves a standard registered release asset');
  globalThis.fetch = async (input) => {
    const url = String(input);
    if (url.startsWith('https://api.github.com/repos/')) return new Response(JSON.stringify({ tag_name: 'v5.6.1', assets: [{ name: asset, browser_download_url: `https://maintenance.invalid/${asset}`, size: payload.length }] }), { status: 200 });
    assert.equal(url, `https://maintenance.invalid/${asset}`);
    duringDownload?.();
    return new Response(payload, { status: 200, headers: { 'content-length': String(payload.length) } });
  };
  try { return await action(); } finally { globalThis.fetch = original; }
}
